// Every word of a book (title, lines, bubbles, questions) uses only its stage's vowels: e2e/library.spec.ts.
// So stage א has no "אֶת", "שֶׁל", "יֵשׁ", "הוּא", "אֲנִי", and no plural past ("בָּאוּ"): its books lean on
