// The cast, the same emoji in every book (a bubble's `who` is the speaker's emoji in the page's picture):
//   👧 דָּנָה · 🐢 הַצָּב (the library's hero, slow and wise) · 🧔 אַבָּא · 👩 אִמָּא · 👴 סַבָּא · 👵 סַבְתָּא
//   🐰 אַרְנָב · 🐭 עַכְבָּר · 🐒 הַקּוֹף · 🐻 הַדֹּב · 🕊️ הַיּוֹנָה · 🐝 הַדְּבוֹרָה · 🐱 מִיצִי · 🐘 הַפִּיל
//   🐦 צִפּוֹר · 🐕 שׁוֹקוֹ הַכֶּלֶב · 🦁 הָאַרְיֵה · 👦 נֹעַם · 🦉 הַיַּנְשׁוּף
//
// Audio: one mp3 per line / bubble / question (scripts/gen-story-audio.ts, keys from libraryAudioItems()).
