import { READING_STAGES, type StageId } from "../lib/decodable.ts";

export { READING_STAGES, type StageId };

export type Bubble = { /** The speaker: one emoji of the page's picture. */ who: string; text: string };

export type BookPage = {
  /** 1–4 short lines, full nikud. */
  lines: string[];
  /** The picture: 1–4 emoji (the speaker is one of them). */
  pic: string;
  /** A big faded backdrop (the sea, the night, a tree…). */
  bg?: string;
  /** What someone in the picture says (shown in a speech bubble over them). */
  say?: Bubble;
};

export type BookQuestion =
  /** "What happened?": the question and 3 picture answers; the first one is right (shuffled on screen). */
  | { kind: "pic"; text: string; options: [string, string, string] }
  /** "Who said it?": a bubble from the book and 3 faces; the first one is right. */
  | { kind: "who"; quote: string; options: [string, string, string] };

export type Book = {
  id: string;
  stage: StageId;
  title: string;
  /** The cover picture; also the sticker the child gets on the shelf. */
  cover: string;
  pages: BookPage[];
  questions: BookQuestion[];
};

type PageOpts = { bg?: string; say?: [who: string, text: string] };
const pg = (pic: string, lines: string[], o: PageOpts = {}): BookPage => ({
  lines,
  pic,
  ...(o.bg && { bg: o.bg }),
  ...(o.say && { say: { who: o.say[0], text: o.say[1] } }),
});
const pic = (text: string, options: [string, string, string]): BookQuestion => ({ kind: "pic", text, options });
const who = (quote: string, options: [string, string, string]): BookQuestion => ({ kind: "who", quote, options });

function book(stage: StageId, n: number, title: string, cover: string, pages: BookPage[], questions: BookQuestion[]): Book {
  return { id: `${stage}-${n}`, stage, title, cover, pages, questions };
}

