export const BOOK_BY_ID = Object.fromEntries(LIBRARY.map((b) => [b.id, b])) as Record<string, Book>;

export function booksOf(stage: StageId): Book[] {
  return LIBRARY.filter((b) => b.stage === stage);
}

export const bookHref = (b: Book) => `/play/i-read/${b.id}`;

/** The next book in library order (the next stage's first after a stage's last). */
export function nextBook(b: Book): Book | undefined {
  return LIBRARY[LIBRARY.indexOf(b) + 1];
}

/** Audio keys: "i-read/<book>/<page>-<line>" (1-based), "…/<page>-say" for a bubble, "…/q<n>" for a picture question. */
export const lineKey = (bookId: string, page: number, line: number) => `i-read/${bookId}/${page + 1}-${line + 1}`;
export const bubbleKey = (bookId: string, page: number) => `i-read/${bookId}/${page + 1}-say`;
export const questionKey = (bookId: string, q: number) => `i-read/${bookId}/q${q + 1}`;

/** Everything the voice reads, in order (a "who said it?" quote reuses its bubble's audio). Titles are not voiced. */
export function libraryAudioItems(): { key: string; text: string }[] {
  return LIBRARY.flatMap((b) => [
    ...b.pages.flatMap((p, i) => [
      ...p.lines.map((text, j) => ({ key: lineKey(b.id, i, j), text })),
      ...(p.say ? [{ key: bubbleKey(b.id, i), text: p.say.text }] : []),
    ]),
    ...b.questions.flatMap((q, i) => (q.kind === "pic" ? [{ key: questionKey(b.id, i), text: q.text }] : [])),
  ]);
}

/** Every text of a book a child reads (for the decodability check). */
export function bookTexts(b: Book): string[] {
  return [
    b.title,
    ...b.pages.flatMap((p) => [...p.lines, ...(p.say ? [p.say.text] : [])]),
    ...b.questions.map((q) => (q.kind === "pic" ? q.text : q.quote)),
  ];
}
