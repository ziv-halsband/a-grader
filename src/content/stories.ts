// 📚 Decodable read-along stories: 6 per nikud world (36 in all).
// DRAFT (mom): every story, sentence, picture and question here is a draft for mom to check.
//
// Decodable (founder's choice): a story in world N uses ONLY the vowels of worlds 1..N (NIKUD_TOPICS order):
//   kamatz-patach: ָ ַ · tsere-segol: + ֵ ֶ · hiriq: + ִ · holam: + ֹ / וֹ · shuruk-kubutz: + וּ ֻ · shva: + ְ (and the hatafs).
// Dagesh, shin/sin dots and final letters are always allowed. A letter may stay bare only at the end of a word,
// before a vowel-vav (וֹ, וּ), as a yod after ִ/ֵ/ֶ ("פִּיל", "בֵּיצָה") or as a silent alef after a vowel ("קוֹרֵאת").
// Word-final ה after a vowel ("דָּנָה") is a bare final letter. lib/decodable.ts checks all of this (e2e/stories.spec.ts).
//
// So in the kamatz/patach world there is no "and" (וְ / וּ) and no feminine past with shva ("אָכְלָה"):
// the stories lean on hollow verbs ("בָּאָה", "שָׂמָה", "רָצָה") and short verbless sentences ("דָּנָה בַּגַּן.").
//
// Recurring friends: דָּנָה, אַבָּא, סַבָּא and her turtle הַצָּב (from story 1); הַכֶּלֶב (world 2), אִמָּא and the cat
// מִיצִי (world 3), the camel, the elephant and the monkey come back to the birthday (world 5).
//
// Audio: one mp3 per page (+ the question) with word timings, made by scripts/gen-story-audio.ts (story-audio.json).
// Keep the text short: every character costs ElevenLabs credits.

/** Ids of NIKUD_TOPICS (content/curriculum.ts), in teaching order. */
export const STORY_WORLDS = ["kamatz-patach", "tsere-segol", "hiriq", "holam", "shuruk-kubutz", "shva"] as const;
export type StoryWorld = (typeof STORY_WORLDS)[number];

export type StoryPage = {
  /** One short sentence, full nikud. */
  text: string;
  /** The picture: one big emoji scene (1–3 emoji). */
  pic: string;
  /** A big faded backdrop behind the picture (the sea, a house, a tree…). */
  bg?: string;
};

export type Story = {
  id: string;
  world: StoryWorld;
  title: string;
  /** The book's cover on the shelf; also the sticker the child gets for reading it. */
  cover: string;
  pages: StoryPage[];
  /** "What happened?": a question and 3 picture answers; the first one is right (shuffled on screen). */
  question: { text: string; options: [string, string, string] };
};

type P = [text: string, pic: string, bg?: string];

function story(world: StoryWorld, n: number, title: string, cover: string, pages: P[], q: [string, [string, string, string]]): Story {
  return {
    id: `${world}-${n}`,
    world,
    title,
    cover,
    pages: pages.map(([text, pic, bg]) => ({ text, pic, ...(bg && { bg }) })),
    question: { text: q[0], options: q[1] },
  };
}

