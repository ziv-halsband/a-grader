export const STORY_BY_ID = Object.fromEntries(STORIES.map((s) => [s.id, s])) as Record<string, Story>;

export function storiesOf(world: string): Story[] {
  return STORIES.filter((s) => s.world === world);
}

export function isStoryWorld(w: string): w is StoryWorld {
  return (STORY_WORLDS as readonly string[]).includes(w);
}

/** The words of a sentence as shown (punctuation stays on its word): split on spaces. */
export function storyWords(text: string): string[] {
  return text.split(/\s+/).filter(Boolean);
}

/** Audio key of a page ("kamatz-patach-1/2", 1-based) or of the question ("…/q"). */
export function storyAudioKey(storyId: string, page: number | "q"): string {
  return `${storyId}/${page === "q" ? "q" : page + 1}`;
}

/** Everything the voice reads, in order: each page, then the question. (Titles are not voiced: credits.) */
export function storyAudioItems(): { key: string; text: string }[] {
  return STORIES.flatMap((s) => [
    ...s.pages.map((p, i) => ({ key: storyAudioKey(s.id, i), text: p.text })),
    { key: storyAudioKey(s.id, "q"), text: s.question.text },
  ]);
}
